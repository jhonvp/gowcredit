// Trains the T2 line classifier (ADR 0003): make train-classifier.
//
// Labels come from T0 itself, on documents whose T0 output passes every blocking validator: their
// table lines are confirmed by the document's own arithmetic, so no hand labeling is needed. Writes
// src/infrastructure/extraction/t2/line-model.generated.ts (weights only, no document data) and
// eval/reports/classifier.md. Metrics are in-sample: leave-one-bank-out is an agreed cut (PLAN.md).
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { formatMxn } from '../src/domain/shared/money';
import { totalCredits, totalDebits } from '../src/domain/statement/bank-statement';
import { validateStatement } from '../src/domain/validation/statement-validators';
import { PopplerTextAdapter } from '../src/infrastructure/extraction/pdf/poppler-text.adapter';
import { T0StatementExtractor } from '../src/infrastructure/extraction/t0/t0-statement-extractor';
import { QUALITY_THRESHOLD, repairPage } from '../src/infrastructure/extraction/t0/text-quality';
import {
  CLASSES,
  FEATURE_NAMES,
  pageFeatures,
} from '../src/infrastructure/extraction/t2/line-features';
import { predict, train } from '../src/infrastructure/extraction/t2/softmax';
import { T2ClassifierStatementExtractor } from '../src/infrastructure/extraction/t2/t2-classifier-statement-extractor';

const ROOT = resolve(__dirname, '../../..');
const DATASET = resolve(process.env.EVAL_DATASET_DIR ?? join(ROOT, 'facturas'));
const OUT_MODEL = resolve(__dirname, '../src/infrastructure/extraction/t2/line-model.generated.ts');
const OUT_REPORT = join(ROOT, 'eval/reports/classifier.md');

async function main(): Promise<void> {
  if (!existsSync(DATASET)) throw new Error(`Dataset not found: ${DATASET}`);
  const poppler = new PopplerTextAdapter();
  const t0 = new T0StatementExtractor();
  const X: number[][] = [];
  const y: number[] = [];
  const docs: {
    file: string;
    text: Awaited<ReturnType<typeof poppler.extract>>;
    rows: number;
    credits: number;
    debits: number;
  }[] = [];
  const skipped: string[] = [];

  for (const file of readdirSync(DATASET)
    .filter((f) => f.endsWith('.pdf'))
    .sort()) {
    const text = await poppler.extract(readFileSync(join(DATASET, file)));
    const { extraction, labels } = t0.extractWithLabels(text);
    if (!validateStatement(extraction.statement).passed) {
      skipped.push(file);
      continue;
    }
    const byLine = new Map(labels.map((l) => [`${l.page}:${l.line}`, l.label]));
    for (const page of text.pages.map(repairPage)) {
      if (page.quality < QUALITY_THRESHOLD) continue;
      const feats = pageFeatures(page.lines);
      page.lines.forEach((line, i) => {
        if (line.trim() === '') return;
        X.push(feats[i] as number[]);
        y.push(CLASSES.indexOf(byLine.get(`${page.number}:${i}`) ?? 'other'));
      });
    }
    const s = extraction.statement;
    docs.push({
      file,
      text,
      rows: s.transactions.length,
      credits: totalCredits(s),
      debits: totalDebits(s),
    });
  }

  const started = Date.now();
  const model = train(X, y, CLASSES, FEATURE_NAMES);
  const trainMs = Date.now() - started;

  // In-sample per-class precision/recall.
  const pred = X.map((x) => CLASSES.indexOf(predict(model, x).label as (typeof CLASSES)[number]));
  const perClass = CLASSES.map((name, c) => {
    const tp = pred.filter((p, i) => p === c && y[i] === c).length;
    const fp = pred.filter((p, i) => p === c && y[i] !== c).length;
    const fn = pred.filter((p, i) => p !== c && y[i] === c).length;
    return {
      name,
      support: y.filter((v) => v === c).length,
      precision: tp / (tp + fp || 1),
      recall: tp / (tp + fn || 1),
    };
  });

  // Robustness: T2 alone must rebuild the rows of each training document (no T0 header rules).
  const t2 = new T2ClassifierStatementExtractor(model);
  const rebuild: string[] = [];
  for (const d of docs) {
    const base = await t0.extract(d.text);
    const out = await t2.extract(d.text, {
      documentId: d.file,
      pdf: new Uint8Array(),
      previous: null,
    });
    if ('skipped' in out) {
      rebuild.push(`| ${d.file} | skipped (${out.skipped}) | | |`);
      continue;
    }
    const s = { ...out.statement, summary: base.statement.summary };
    const ok = validateStatement(s).passed;
    rebuild.push(
      `| ${d.file} | ${s.transactions.length}/${d.rows} | ${formatMxn(totalCredits(s))} / ${formatMxn(d.credits)} | ${ok ? 'yes' : 'no'} |`,
    );
  }

  writeFileSync(
    OUT_MODEL,
    `// Generated by scripts/train-classifier.ts (make train-classifier). Do not edit.\n` +
      `// Trained ${new Date().toISOString().slice(0, 10)} on ${X.length} lines from ${docs.length} documents.\n` +
      `import type { SoftmaxModel } from './softmax';\n\n` +
      `export const LINE_MODEL: SoftmaxModel = ${JSON.stringify(roundModel(model), null, 2)};\n`,
  );
  const pct = (v: number) => `${(100 * v).toFixed(1)}%`;
  const report = [
    '# T2 line classifier — training report',
    '',
    `Generated by \`make train-classifier\`. Labels come from T0 on documents whose T0 output passes every`,
    `blocking validator (${docs.length} used; skipped: ${skipped.join(', ') || 'none'}). ${X.length} non-blank lines,`,
    `${FEATURE_NAMES.length} features, softmax regression, trained in ${trainMs} ms.`,
    '',
    '**All numbers are in-sample** (leave-one-bank-out validation is an agreed cut, see PLAN.md).',
    '',
    '| Class | Support | Precision | Recall |',
    '|---|---|---|---|',
    ...perClass.map((c) => `| ${c.name} | ${c.support} | ${pct(c.precision)} | ${pct(c.recall)} |`),
    '',
    '## Rebuilding rows without T0 table rules',
    '',
    'T2 alone (classifier + row builder, T0 summary) on each training document:',
    '',
    '| Document | Rows (T2/T0) | Credits (T2/T0) | Passes validators |',
    '|---|---|---|---|',
    ...rebuild,
    '',
  ].join('\n');
  writeFileSync(OUT_REPORT, report);
  console.log(report);
}

const roundModel = (m: ReturnType<typeof train>) => ({
  ...m,
  mean: m.mean.map((v) => +v.toFixed(6)),
  std: m.std.map((v) => +v.toFixed(6)),
  weights: m.weights.map((w) => w.map((v) => +v.toFixed(6))),
});

main().catch((e: unknown) => {
  console.error(e);
  process.exit(1);
});
